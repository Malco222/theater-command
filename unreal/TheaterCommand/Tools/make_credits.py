#!/usr/bin/env python3
"""
Writes Sounds/Real/CREDITS.md from Sounds/Real/credits.json: the one list of the real recordings the 3D game plays,
the recordings each was cut from, and the licence and the credit each is owed. The game's own credits (OPTIONS, the
last section) are read from the same list, so the two never differ. Run it after changing the list:

    python3 Tools/make_credits.py
"""
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
folder = os.path.join(here, "..", "Sounds", "Real")
with open(os.path.join(folder, "credits.json"), encoding="utf-8") as file:
    listed = json.load(file)

lines = [
    "# Real recordings in the 3D game: sources, licences and credits",
    "",
    "Made from `credits.json` by `Tools/make_credits.py`. Do not edit this file: change the list and run the tool.",
    "",
    "Brian approved these recordings on 18 November 2026. They are cut and mixed for this game by the project's sound",
    "thread from the recordings below; nothing here is synthesised and nothing comes from a film, a series or a game.",
    "The game is for personal use only.",
    "",
    "| The game's moment | Recording | Cut from | Shared on | Licence | Credit owed |",
    "|---|---|---|---|---|---|",
]
owed = {}
for sound in listed["sounds"]:
    for source in sound["sources"]:
        if source.get("creator", "").strip().lower() == "none":
            source["creator"] = ""  # a few entries say "none" for no credit owed: never list "none" as a creator
        title = source["title"].replace("|", "/")
        link = f"[{title}]({source['page']})" if source.get("page") else title
        lines.append(f"| `{sound['moment']}` | `{sound['recording']}.wav` | {link} | {source.get('archive', '')} | {source['licence']} | {source['creator'] or 'none'} |")
        # ("none" is how some rows say no one is named: nothing is owed to a person called none)
        if source["creator"] and source["creator"] != "none":
            owed.setdefault(source["creator"], [])
            if (source["title"], source["licence"]) not in owed[source["creator"]]:
                owed[source["creator"]].append((source["title"], source["licence"]))

lines += ["", "## Credits owed", ""]
for creator in sorted(owed, key=str.lower):
    licences = {licence for _, licence in owed[creator]}
    if len(licences) == 1:
        lines.append(f"- **{creator}** " + ", ".join(f'"{title}"' for title, _ in owed[creator]) + f" · {licences.pop()}")
    else:
        lines.append(f"- **{creator}** " + ", ".join(f'"{title}" · {licence}' for title, licence in owed[creator]))
lines.append("")

with open(os.path.join(folder, "CREDITS.md"), "w", encoding="utf-8") as file:
    file.write("\n".join(lines))
print(f"CREDITS.md written: {sum(len(s['sources']) for s in listed['sounds'])} sources, {len(owed)} creators credited")
