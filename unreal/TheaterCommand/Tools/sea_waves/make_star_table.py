"""
The night sky's stars (the release 2 ocean plan, step 11(f): the moon and stars on one unfogged dome; look bible S7,
"Night at sea"). Writes Source/TheaterCommand/Battle/SeaNightStars.inl, the real naked-eye sky, from the Yale Bright
Star Catalogue, 5th revised edition (Hoffleit and Warren, 1991; NASA's Astronomical Data Center, catalogue V/50), the
public catalogue of every star of magnitude 6.5 and brighter. The sea's night sky shows the stars that were really over
the battle at its hour, not a seeded scatter: Orion over a January convoy, the Southern Cross over the Solomons.

Each row: right ascension (hours) and declination (degrees) at the catalogue's epoch, J2000, the visual magnitude V, and
the star's colour temperature (kelvin, the catalogue file's own "K" column; 0 where it gives none). Only stars of V 5.5
and brighter are kept: what a sailor sees on a clear night at sea with the haze low on the horizon (a dark country sky
reaches 6 to 6.5; the sea's salt haze and a ship's own lights, even darkened, take about a magnitude off).

Usage: python3 -I Tools/sea_waves/make_star_table.py CATALOGUE.json OUT.inl
CATALOGUE.json is the catalogue as a JSON list of {"RA": "00h 05m 09.9s", "Dec": "+45 13' 45\"", "V": "6.70", "K": "9750"}
rows (bsc5-short.json, as published with the catalogue's JSON transcription). The input is only read: no code in it runs.
"""
import json
import re
import sys

LIMIT = 5.5  # (the faintest magnitude kept)


def hours_of(text):
    """'00h 05m 09.9s' -> hours."""
    parts = re.findall(r"[-+]?\d+(?:\.\d+)?", text)
    if len(parts) != 3:
        raise ValueError(f"right ascension not read: {text!r}")
    h, m, s = (float(p) for p in parts)
    return h + m / 60.0 + s / 3600.0


def degrees_of(text):
    """'+45° 13′ 45″' -> degrees (its sign from the first character, so -00° 30′ is negative)."""
    parts = re.findall(r"\d+(?:\.\d+)?", text)
    if len(parts) != 3:
        raise ValueError(f"declination not read: {text!r}")
    d, m, s = (float(p) for p in parts)
    sign = -1.0 if text.strip().startswith(("-", "−")) else 1.0
    return sign * (d + m / 60.0 + s / 3600.0)


def main(source, out):
    with open(source, encoding="utf-8") as f:
        rows = json.load(f)
    if not isinstance(rows, list):
        raise SystemExit("the catalogue is not a list of stars")
    kept = []
    for row in rows:
        if not isinstance(row, dict):
            continue
        v = row.get("V")
        if v in (None, ""):
            continue
        try:
            mag = float(v)
        except ValueError:
            continue
        if mag > LIMIT:
            continue
        ra = hours_of(str(row["RA"]))
        dec = degrees_of(str(row["Dec"]))
        try:
            kelvin = float(row.get("K") or 0.0)
        except ValueError:
            kelvin = 0.0
        if not (0.0 <= ra < 24.0) or not (-90.0 <= dec <= 90.0) or not (-2.0 <= mag <= LIMIT):
            raise SystemExit(f"a row out of range: {row!r}")
        kept.append((ra, dec, mag, kelvin))
    # (brightest first, so a reader that wants fewer takes the head of the list)
    kept.sort(key=lambda r: (r[2], r[0], r[1]))
    lines = [
        "// Generated by Tools/sea_waves/make_star_table.py from the Yale Bright Star Catalogue, 5th revised edition",
        "// (Hoffleit and Warren 1991; NASA ADC catalogue V/50): every star of visual magnitude %.1f and brighter," % LIMIT,
        "// brightest first. Each row: right ascension (hours, J2000), declination (degrees, J2000), V, colour (kelvin, 0",
        "// where the catalogue gives none). Do not edit by hand: run the script again.",
        "// %d stars." % len(kept),
    ]
    for ra, dec, mag, kelvin in kept:
        lines.append("{ %.5ff, %.4ff, %.2ff, %.1ff }," % (ra, dec, mag, kelvin))
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(kept)} stars of V {LIMIT} and brighter written to {out}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
